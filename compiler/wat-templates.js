'use strict';

function indent(text, level = 1) {
  const padding = '  '.repeat(level);
  return String(text)
    .split('\n')
    .map((line) => (line.length > 0 ? `${padding}${line}` : line))
    .join('\n');
}

function renderGlobal(globalDef) {
  const typeExpr = globalDef.mutable === false
    ? globalDef.watType
    : `(mut ${globalDef.watType})`;
  const initExpr = globalDef.initExpression || `(${globalDef.watType}.const 0)`;
  return [
    `  ;; global ${globalDef.name}`,
    `  (global $${globalDef.name} ${typeExpr} ${initExpr})`
  ].join('\n');
}

function renderInstructionLines(instructions, baseIndent = 2) {
  const lines = [];
  let indentLevel = baseIndent;

  for (const instruction of instructions) {
    const text = String(instruction || '').trim();
    if (!text) continue;

    if (/^(end|else)\b/.test(text)) {
      indentLevel = Math.max(baseIndent, indentLevel - 1);
    }

    lines.push(`${'  '.repeat(indentLevel)}${text}`);

    if (/^(block|loop|if)\b/.test(text)) {
      indentLevel += 1;
    } else if (/^else\b/.test(text)) {
      indentLevel += 1;
    }
  }

  return lines;
}

function renderFunction(functionDef) {
  const signatureParts = [`(func $${functionDef.name}`];

  for (const param of functionDef.params || []) {
    signatureParts.push(`(param $${param.name} ${param.watType})`);
  }

  if (functionDef.resultType) {
    signatureParts.push(`(result ${functionDef.resultType})`);
  }

  const lines = [
    `  ;; function ${functionDef.name}`,
    `  ${signatureParts.join(' ')}`
  ];

  for (const local of functionDef.locals || []) {
    lines.push(`    (local $${local.name} ${local.watType})`);
  }

  const bodyInstructions = functionDef.instructions && functionDef.instructions.length > 0
    ? functionDef.instructions
    : ['nop'];

  lines.push(...renderInstructionLines(bodyInstructions, 2));

  lines.push('  )');
  return lines.join('\n');
}

function escapeWatData(bytes = []) {
  return bytes
    .map((value) => {
      const byte = Number(value) & 0xFF;
      if (byte >= 0x20 && byte <= 0x7E && byte !== 0x22 && byte !== 0x5C) {
        return String.fromCharCode(byte);
      }
      return `\\${byte.toString(16).padStart(2, '0')}`;
    })
    .join('');
}

function renderDataSegment(segment) {
  return `  (data (i32.const ${segment.offset || 0}) "${escapeWatData(segment.bytes || [])}")`;
}

function renderExport(exportDef) {
  return `  (export "${exportDef.exportName}" (${exportDef.kind} $${exportDef.internalName}))`;
}

function renderModule(moduleDef) {
  const lines = [
    ';; Generated by MaiaC',
    ';; Template backend: human-readable WAT',
    ';; Style inspired by maiawasm/assembler/tests/fixtures',
    '',
    '(module'
  ];

  const sections = [];

  if (moduleDef.memories && moduleDef.memories.length > 0) {
    sections.push(moduleDef.memories.map((memory) => `  (memory $${memory.name} ${memory.pages || 1})`).join('\n'));
  }

  if (moduleDef.globals && moduleDef.globals.length > 0) {
    sections.push(moduleDef.globals.map(renderGlobal).join('\n\n'));
  }

  if (moduleDef.dataSegments && moduleDef.dataSegments.length > 0) {
    sections.push(moduleDef.dataSegments.map(renderDataSegment).join('\n'));
  }

  if (moduleDef.functions && moduleDef.functions.length > 0) {
    sections.push(moduleDef.functions.map(renderFunction).join('\n\n'));
  }

  if (moduleDef.exports && moduleDef.exports.length > 0) {
    sections.push(moduleDef.exports.map(renderExport).join('\n'));
  }

  if (sections.length > 0) {
    lines.push(sections.join('\n\n'));
  }

  lines.push(')');
  return lines.join('\n');
}

module.exports = {
  indent,
  renderGlobal,
  renderFunction,
  renderDataSegment,
  renderExport,
  renderModule
};
